interface I18n {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  errorText: (error: unknown) => string;
}

const Context = createContext<I18n | null>(null);

function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem('votria.lang');
    if (saved === 'pt' || saved === 'en') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(initialLanguage);
  const setLang = useCallback((next: Language) => {
    setLangState(next);
    document.documentElement.lang = next === 'pt' ? 'pt-BR' : 'en';
    try {
      localStorage.setItem('votria.lang', next);
    } catch {
      /* storage unavailable */
    }
  }, []);
  const value = useMemo<I18n>(() => {
    const table = lang === 'pt' ? pt : en;
    const t = (key: Key, vars: Record<string, string | number> = {}) =>
      table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
    const errorText = (error: unknown) => {
      if (error instanceof ApiError) {
        if (lang === 'en' && errorsEn[error.code]) return errorsEn[error.code];
        if (typeof error.detail === 'string' && error.detail) return error.detail;
        return (
          errorsEn[error.code] ??
          (lang === 'pt' ? 'Não foi possível concluir a operação.' : 'The operation could not be completed.')
        );
      }
      return error instanceof Error ? error.message : String(error);
    };
    return { lang, setLang, t, errorText };
  }, [lang, setLang]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useI18n(): I18n {
  const value = useContext(Context);
  if (!value) throw new Error('useI18n outside I18nProvider');
  return value;
}

